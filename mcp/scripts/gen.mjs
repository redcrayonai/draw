// Writes the two files the Worker derives from the module, so neither drifts:
//
//   src/reducers.gen.ts  positional argument lists of the reducers it calls,
//                        read from agent/src/module_bindings (spec §3 drift)
//   src/errors.gen.ts    every sentence the module can refuse a call with, as
//                        regexes, so scrub() passes a 530 body through only
//                        when it is one of ours (spec §3 Templates)
//
// `node scripts/gen.mjs` rewrites them; `node scripts/gen.mjs --check` exits 1
// when either is stale (gen.test.ts runs the check in `pnpm test`).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ts = require('typescript');
const root = new URL('../../', import.meta.url);
const read = rel => readFileSync(new URL(rel, root), 'utf8');

// The reducers the hosted tools call, as the module names them over HTTP.
export const REDUCERS = [
  'add_change_note', 'add_code_ref', 'anchor_chart', 'clear_board_window', 'open_incident', 'set_board_window', 'unanchor_chart', 'add_repo_files', 'add_threat', 'arrive_at_checkpoint', 'claim_marks', 'create_architecture_proposal', 'create_chart', 'create_edge', 'create_icon_node',
  'create_node', 'create_requested_board', 'delete_edge', 'delete_node', 'grant_hosted_agent_board', 'join_board', 'link_hosted_agent', 'mark_checkpoint', 'merge_architecture_proposal', 'move_node',
  'offer_agent_link', 'open_shared_link', 'plan_route', 'play_trace', 'remove_change_note', 'remove_code_ref', 'remove_threat', 'reply_mark', 'reroute', 'reset_demo',
  'resize_node', 'set_change_note_readers', 'set_chart_data', 'set_code_ref_hashes', 'set_edge_evidence_code', 'set_edge_hidden', 'set_edge_latency', 'set_node_doc', 'set_node_hidden', 'set_node_icon',
  'set_selection', 'set_session_remote', 'start_session', 'submit_architecture_proposal', 'update_change_note', 'update_code_ref', 'update_code_ref_and_focus', 'update_edge_evidence', 'update_node', 'update_threat',
];

function reducerArgs(name) {
  let src;
  try {
    src = read(`agent/src/module_bindings/${name}_reducer.ts`);
  } catch {
    return undefined;
  }
  const body = src.slice(src.indexOf('export default {'));
  return [...body.matchAll(/^ {2}(\w+): __t\.(option\(__t\.)?(\w+)\(/gm)].map(([, key, option, type]) => [key, type, Boolean(option)]);
}

function genReducers() {
  const rows = [];
  for (const name of REDUCERS) {
    const args = reducerArgs(name);
    if (!args) throw new Error(`no bindings for reducer ${name}`);
    rows.push(`  ${name}: [${args.map(([k, t, o]) => `['${k}', '${t}', ${o}]`).join(', ')}],`);
  }
  return `// GENERATED by mcp/scripts/gen.mjs from agent/src/module_bindings. Do not edit.
// [argument, type, optional] in the order /call takes them.
export const REDUCER_ARGS = {
${rows.join('\n')}
} as const;
`;
}

// --- module refusal sentences -------------------------------------------------

const MODULE_FILES = ['index.ts', 'chart-contracts.ts', 'change-notes.ts', 'architecture.ts', 'health-rules.ts', 'threats.ts', 'node-icons.ts', 'marks.ts', 'workspaces.ts', 'workspace-policy.ts', 'workspace-service-accounts.ts', 'workspace-service-policy.ts'];

function parse(file) {
  return ts.createSourceFile(file, read(`module/src/${file}`), ts.ScriptTarget.Latest, true);
}

const HOLE = '\u0000';
const escape = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Module-scope constants by name across the module files, for
// `new SenderError(CHART_KIND_RULE)`. Locals and parameters stay holes.
function constants(files) {
  const out = new Map();
  for (const sf of files) {
    for (const stmt of sf.statements) {
      if (!ts.isVariableStatement(stmt) || !(stmt.declarationList.flags & ts.NodeFlags.Const)) continue;
      for (const d of stmt.declarationList.declarations) if (ts.isIdentifier(d.name) && d.initializer) out.set(d.name.text, d.initializer);
    }
  }
  return out;
}

// An expression as the strings it can evaluate to, with HOLE for anything dynamic.
function texts(node, consts, depth = 0) {
  if (depth > 8) return [HOLE];
  if (ts.isParenthesizedExpression(node)) return texts(node.expression, consts, depth + 1);
  if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) return [node.text];
  if (ts.isTemplateExpression(node)) {
    let parts = [node.head.text];
    for (const span of node.templateSpans) {
      const inner = texts(span.expression, consts, depth + 1);
      parts = parts.flatMap(p => inner.map(i => p + i + span.literal.text));
    }
    return parts;
  }
  if (ts.isBinaryExpression(node) && node.operatorToken.kind === ts.SyntaxKind.PlusToken) {
    const l = texts(node.left, consts, depth + 1);
    const r = texts(node.right, consts, depth + 1);
    return l.flatMap(a => r.map(b => a + b));
  }
  if (ts.isConditionalExpression(node)) return [...texts(node.whenTrue, consts, depth + 1), ...texts(node.whenFalse, consts, depth + 1)];
  if (ts.isIdentifier(node) && consts.has(node.text)) return texts(consts.get(node.text), consts, depth + 1);
  return [HOLE];
}

function genErrors() {
  const files = MODULE_FILES.map(parse);
  const consts = constants(files);
  const found = new Set();
  const add = text => {
    // A sentence that is all hole (`new SenderError(e.message)`) says nothing; its sources are collected below.
    if (text.replaceAll(HOLE, '').trim().length >= 6) found.add(text);
  };
  for (const sf of files) {
    sf.forEachChild(function visit(node) {
      // new SenderError(<text>) anywhere; Error texts and `error:` results of the
      // validators whose message index.ts rethrows as a SenderError.
      if (ts.isNewExpression(node) && ts.isIdentifier(node.expression) && node.arguments?.length) {
        const name = node.expression.text;
        if (name === 'SenderError' || (name === 'Error' && sf.fileName !== 'index.ts')) texts(node.arguments[0], consts).forEach(add);
      }
      if (sf.fileName === 'chart-contracts.ts' && ts.isPropertyAssignment(node) && ts.isIdentifier(node.name) && node.name.text === 'error') {
        texts(node.initializer, consts).forEach(add);
      }
      node.forEachChild(visit);
    });
  }
  const patterns = [...found]
    .map(t => `^${t.split(HOLE).map(escape).join('[^]*?')}$`)
    .sort();
  return `// GENERATED by mcp/scripts/gen.mjs from module/src (${MODULE_FILES.join(', ')}). Do not edit.
// Every sentence the module refuses a call with; a 530 body passes scrub() only if one matches.
export const SENDER_ERRORS: readonly RegExp[] = [
${patterns.map(p => `  /${p.replaceAll('/', '\\/')}/,`).join('\n')}
];
`;
}

const outputs = { 'mcp/src/reducers.gen.ts': genReducers(), 'mcp/src/errors.gen.ts': genErrors() };

if (process.argv.includes('--check')) {
  const stale = Object.entries(outputs).filter(([rel, text]) => {
    try {
      return read(rel) !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`stale: ${stale.map(([rel]) => rel).join(', ')}; run node mcp/scripts/gen.mjs`);
    process.exit(1);
  }
} else {
  for (const [rel, text] of Object.entries(outputs)) writeFileSync(new URL(rel, root), text);
}
