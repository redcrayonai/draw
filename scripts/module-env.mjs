#!/usr/bin/env node
// Writes module/src/issuers.ts for one environment before a publish (hosted MCP
// spec §8 Item 2, M1.2). Every path that publishes the module runs this first:
// the committed file is the `none` variant, which refuses every sender outside
// service_account.
//
//   node scripts/module-env.mjs <none|local|staging|production> [-- <command> [args...]]
//
// With a command it writes the variant, runs the command, then writes `none`
// back (also when the command fails or is interrupted), so a local publish
// leaves `git status` clean. Without one it only writes the file (CI, whose
// checkout is thrown away).
// shortcut: one file per checkout, so two publishes from one checkout at once
// race on it; run them one after another (CI runs each variant in its own job).
// Upgrade to a per-publish copy of module/ when one checkout must publish in parallel.
//
// Values come from the environment, never from this file:
//   MCP_ORIGIN            the hosted MCP Worker's origin; ours = `${MCP_ORIGIN}/agent-id`
//                         (local default http://localhost:8788; '' elsewhere = no hosted agents yet)
//   BROWSER_ISSUER        the OIDC issuer that signs browser session tokens, exactly as their
//                         iss claim ('' = none)
//   BROWSER_SESSION_CLAIM a claim every browser session token carries and other tokens
//                         of that issuer lack ('' = no such check). An identity provider
//                         whose OAuth tokens share the issuer needs it.
//   APP_ORIGINS           comma-separated canvas and dashboard origins (a session token's azp)
//                         (local default http://localhost:5173,http://localhost:5174)
//   BROWSER_CLIENT_IDS    comma-separated OIDC client ids (VITE_OIDC_CLIENT_ID): a session
//                         token's azp, or its aud when it has no azp ('' = none, as for the hosted service)
//   DB_ISSUERS            comma-separated issuers of tokens the database host signs itself: the
//                         anonymous identities POST /v1/identity mints (canvas guests; 'localhost'
//                         on every host so far, the default) and the database owner's CLI login,
//                         whose SQL connects like any client (deploy-env.yml adds it)
//   REDCRAYON_LIMITS      on|off: the storage limits in module/src/limits.ts (default off: turn
//                         them on per environment once its stored data fits them)
import { writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const FILE = new URL('../module/src/issuers.ts', import.meta.url);
const VARIANTS = ['none', 'local', 'staging', 'production'];

function issuers(variant, env) {
  if (variant === 'none') return { ours: '', browser: '', sessionClaim: '', appOrigins: [], browserClientIds: [], dbIssuers: [], enforce: true, limits: true, variant };
  const local = variant === 'local';
  const limits = env.REDCRAYON_LIMITS || 'off';
  if (!['on', 'off'].includes(limits)) throw new Error(`REDCRAYON_LIMITS must be on or off, not '${limits}'`);
  const mcp = (env.MCP_ORIGIN || (local ? 'http://localhost:8788' : '')).replace(/\/+$/, '');
  const apps = env.APP_ORIGINS || (local ? 'http://localhost:5173,http://localhost:5174' : '');
  return {
    ours: mcp ? `${mcp}/agent-id` : '',
    // byte for byte: the module compares it with a token's iss, and an issuer may end in '/' (Auth0)
    browser: env.BROWSER_ISSUER ?? '',
    sessionClaim: env.BROWSER_SESSION_CLAIM ?? '',
    appOrigins: [...new Set(apps.split(',').map(s => s.trim()).filter(Boolean).map(s => new URL(s).origin))],
    browserClientIds: [...new Set((env.BROWSER_CLIENT_IDS ?? '').split(',').map(s => s.trim()).filter(Boolean))],
    dbIssuers: [...new Set((env.DB_ISSUERS || 'localhost').split(',').map(s => s.trim()).filter(Boolean))],
    // RC-571: staging and production refuse other senders; local only logs them.
    enforce: !local,
    limits: limits === 'on',
    variant,
  };
}

const render = value => `// GENERATED by scripts/module-env.mjs; do not edit by hand.
//
// The committed copy is the \`none\` variant: enforce is true and no issuer is
// known, so onConnect refuses every sender outside service_account. A publish
// that skips scripts/module-env.mjs therefore fails closed instead of opening
// the database. Every publish path writes its variant first:
//   - local (scripts/stdb-test.sh, scripts/dev-dashboard.sh, \`pnpm run publish\`):
//     \`node scripts/module-env.mjs <variant> -- spacetime publish ...\` writes the
//     variant, publishes, then writes \`none\` back, so git status stays clean;
//   - CI (.github/workflows/deploy-env.yml): \`node scripts/module-env.mjs
//     production\` in a checkout that is thrown away.
// module-tests checks that \`node scripts/module-env.mjs none\` reproduces this
// file byte for byte.
export const ISSUERS: {
  ours: string; // our MCP Worker's issuer (agent:, machine:, guest:, service: subjects); '' = none
  browser: string; // the OIDC issuer that signs browser session tokens; '' = none
  sessionClaim: string; // a claim a browser session token must carry; '' = no such check
  appOrigins: string[]; // accepted azp values of browser session tokens
  browserClientIds: string[]; // OIDC client ids: accepted azp values, or aud values of a token without azp
  dbIssuers: string[]; // issuers of tokens the database host signs (anonymous identities, the owner's CLI login)
  enforce: boolean; // refuse other senders (true), or only log them (false)
  limits: boolean; // apply the storage limits in limits.ts (REDCRAYON_LIMITS)
  variant: string;
} = ${JSON.stringify(value, null, 2)};
`;

const [variant, dash, cmd, ...args] = process.argv.slice(2);
if (!VARIANTS.includes(variant) || (dash !== undefined && (dash !== '--' || !cmd))) {
  console.error(`usage: node scripts/module-env.mjs <${VARIANTS.join('|')}> [-- <command> [args...]]`);
  process.exit(2);
}
writeFileSync(FILE, render(issuers(variant, process.env)));
if (!cmd) process.exit(0);

// The child gets Ctrl-C itself; staying alive lets this process restore `none`.
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => {});
const run = spawnSync(cmd, args, { stdio: 'inherit' });
writeFileSync(FILE, render(issuers('none', process.env)));
if (run.error) {
  console.error(`module-env: ${run.error.message}`);
  process.exit(127);
}
process.exit(run.status ?? 1);
